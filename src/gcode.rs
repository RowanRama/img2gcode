//! G-code writing, and reading back for the viewer.

use std::fmt::Write as _;

use crate::config::Config;
use crate::geom::Pt;
use crate::toolpath::{Pass, Path, PathKind, Stats, Toolpaths};

/// Filament length per mm of printed line.
pub fn e_per_mm(cfg: &Config) -> f64 {
    let r = cfg.extrusion.filament_diameter / 2.0;
    cfg.line_width() * cfg.layers.height / (std::f64::consts::PI * r * r) * cfg.extrusion.multiplier
}

/// The job's statistics under `cfg`.
pub fn stats(tp: &Toolpaths, cfg: &Config) -> Stats {
    tp.stats(cfg.machine.print_speed, cfg.machine.travel_speed, e_per_mm(cfg), cfg.extrusion.filament_diameter)
}

fn num(v: f64) -> String {
    let s = format!("{v:.3}");
    let s = s.trim_end_matches('0').trim_end_matches('.');
    if s == "-0" { "0".into() } else { s.into() }
}

fn fill(template: &str, cfg: &Config, tool: usize) -> String {
    // A config saved on Windows may carry CRLF; the G-code is LF throughout.
    template
        .replace("\r\n", "\n")
        .replace("{travel_speed}", &num(cfg.machine.travel_speed))
        .replace("{print_speed}", &num(cfg.machine.print_speed))
        .replace("{tool}", &tool.to_string())
}

fn type_comment(kind: PathKind) -> &'static str {
    match kind {
        PathKind::Perimeter | PathKind::Stroke => ";TYPE:External perimeter",
        PathKind::Infill => ";TYPE:Solid infill",
    }
}

/// The complete G-code file for a job.
pub fn write(tp: &Toolpaths, cfg: &Config, source: &str) -> String {
    let s = stats(tp, cfg);
    let e_mm = e_per_mm(cfg);
    let travel_f = num(cfg.machine.travel_speed);
    let print_f = num(cfg.machine.print_speed);
    let mut out = String::with_capacity(64 * s.points + 4096);
    let ext = tp.extent;
    let _ = writeln!(out, "; generated by img2gcode {} from {source}", env!("CARGO_PKG_VERSION"));
    let _ = writeln!(
        out,
        "; mode: {:?}  size: {:.1} x {:.1} mm  tools: {}  layers: {}",
        cfg.mode,
        ext[2] - ext[0],
        ext[3] - ext[1],
        tp.tool_colors.len(),
        cfg.layers.count
    );
    let _ = writeln!(
        out,
        "; line_width: {:.3} mm  infill: {:.0}% spacing {:.3} mm angle {}  perimeters: {}",
        cfg.line_width(),
        cfg.infill.density,
        cfg.infill_spacing(),
        cfg.infill.angle,
        cfg.layers.perimeters
    );
    let _ = writeln!(
        out,
        "; estimated_time: {:.1} min  print_distance: {:.1} mm  travel_distance: {:.1} mm",
        s.minutes, s.print_mm, s.travel_mm
    );
    let _ = writeln!(out, "; filament: {:.1} mm ({:.2} g PLA)", s.filament_mm, s.filament_g);
    out.push_str(";\n");
    out.push_str(&fill(&cfg.gcode.start, cfg, 0));
    if !out.ends_with('\n') {
        out.push('\n');
    }
    let mut layer = usize::MAX;
    let mut tool = usize::MAX;
    for pass in &tp.passes {
        if pass.paths.is_empty() {
            continue;
        }
        if pass.layer != layer {
            layer = pass.layer;
            let _ = writeln!(out, ";LAYER_CHANGE\n;Z:{}\n;HEIGHT:{}", num(pass.z), num(cfg.layers.height));
        }
        if pass.tool != tool {
            tool = pass.tool;
            let _ = writeln!(out, "; --- Tool {tool} ---");
            out.push_str(&fill(&cfg.gcode.tool_change, cfg, tool));
            if !out.ends_with('\n') {
                out.push('\n');
            }
        }
        out.push_str("G92 E0\n");
        let mut e = 0.0;
        let mut kind = None;
        let lift = num(pass.z + cfg.machine.z_lift);
        let z = num(pass.z);
        for path in &pass.paths {
            let Some(first) = path.points.first() else { continue };
            if kind != Some(path.kind) {
                kind = Some(path.kind);
                out.push_str(type_comment(path.kind));
                out.push('\n');
            }
            let _ = writeln!(out, "G1 Z{lift} F{travel_f}");
            let _ = writeln!(out, "G1 X{} Y{} F{travel_f}", num(first[0]), num(first[1]));
            let _ = writeln!(out, "G1 Z{z} F{travel_f}");
            let _ = writeln!(out, "G1 F{print_f}");
            let mut prev = *first;
            for p in &path.points[1..] {
                e += crate::geom::dist(prev, *p) * e_mm;
                let _ = writeln!(out, "G1 X{} Y{} E{:.5}", num(p[0]), num(p[1]), e);
                prev = *p;
            }
        }
    }
    out.push_str("; End of print\n");
    out.push_str(&fill(&cfg.gcode.end, cfg, 0));
    out
}

/// Read G-code back into toolpaths for viewing. Understands absolute G0/G1
/// moves with X, Y, Z, E; `T<n>` tool changes; G92 E resets; relative
/// extrusion (M83); and `;TYPE:` comments.
pub fn parse(text: &str) -> Toolpaths {
    let mut passes: Vec<Pass> = Vec::new();
    let (mut x, mut y, mut z, mut e) = (0.0f64, 0.0f64, 0.0f64, 0.0f64);
    let mut tool = 0usize;
    let mut relative_e = false;
    let mut kind = PathKind::Perimeter;
    let mut current: Option<Path> = None;
    let mut layers_z: Vec<f64> = Vec::new();
    let mut max_tool = 0;
    let flush = |current: &mut Option<Path>, passes: &mut Vec<Pass>, tool: usize, z: f64, layers_z: &mut Vec<f64>| {
        if let Some(p) = current.take().filter(|p| p.points.len() >= 2) {
            let layer = match layers_z.iter().position(|&lz| (lz - z).abs() < 1e-6) {
                Some(i) => i,
                None => {
                    layers_z.push(z);
                    layers_z.len() - 1
                }
            };
            match passes.last_mut() {
                Some(last) if last.layer == layer && last.tool == tool => last.paths.push(p),
                _ => passes.push(Pass { layer, tool, z, paths: vec![p] }),
            }
        }
    };
    for raw in text.lines() {
        let (code, comment) = raw.split_once(';').unwrap_or((raw, ""));
        if let Some(t) = comment.trim().strip_prefix("TYPE:") {
            kind = if t.to_ascii_lowercase().contains("infill") { PathKind::Infill } else { PathKind::Perimeter };
        }
        let mut words = code.split_whitespace();
        let Some(cmd) = words.next() else { continue };
        let cmd = cmd.to_ascii_uppercase();
        let arg = |words: &[&str], c: char| {
            words
                .iter()
                .find(|w| w.starts_with(c) || w.starts_with(c.to_ascii_lowercase()))
                .and_then(|w| w[1..].parse::<f64>().ok())
        };
        let rest: Vec<&str> = words.collect();
        match cmd.as_str() {
            "G0" | "G1" | "G00" | "G01" => {
                let (nx, ny, nz) =
                    (arg(&rest, 'X').unwrap_or(x), arg(&rest, 'Y').unwrap_or(y), arg(&rest, 'Z').unwrap_or(z));
                let extruding = match arg(&rest, 'E') {
                    Some(ne) if relative_e => ne > 0.0,
                    Some(ne) => {
                        let ext = ne > e + 1e-9;
                        e = ne;
                        ext
                    }
                    None => false,
                };
                if (nz - z).abs() > 1e-9 {
                    flush(&mut current, &mut passes, tool, z, &mut layers_z);
                    z = nz;
                }
                let moved = (nx - x).abs() > 1e-9 || (ny - y).abs() > 1e-9;
                if extruding && moved {
                    let path = current.get_or_insert_with(|| Path { kind, points: vec![[x, y]] as Vec<Pt> });
                    path.points.push([nx, ny]);
                } else if moved {
                    flush(&mut current, &mut passes, tool, z, &mut layers_z);
                }
                (x, y) = (nx, ny);
            }
            "G92" => {
                if let Some(ne) = arg(&rest, 'E') {
                    e = ne;
                }
            }
            "M82" => relative_e = false,
            "M83" => relative_e = true,
            c if c.starts_with('T') => {
                if let Ok(t) = c[1..].parse::<usize>() {
                    flush(&mut current, &mut passes, tool, z, &mut layers_z);
                    tool = t;
                    max_tool = max_tool.max(t);
                }
            }
            _ => {}
        }
    }
    flush(&mut current, &mut passes, tool, z, &mut layers_z);
    let mut ext = [f64::MAX, f64::MAX, f64::MIN, f64::MIN];
    for p in passes.iter().flat_map(|p| &p.paths).flat_map(|p| &p.points) {
        ext = [ext[0].min(p[0]), ext[1].min(p[1]), ext[2].max(p[0]), ext[3].max(p[1])];
    }
    if ext[0] > ext[2] {
        ext = [0.0, 0.0, 1.0, 1.0];
    }
    Toolpaths { passes, tool_colors: crate::default_tool_colors(max_tool + 1), extent: ext }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn job() -> Toolpaths {
        Toolpaths {
            passes: vec![
                Pass {
                    layer: 0,
                    tool: 0,
                    z: 3.0,
                    paths: vec![
                        Path {
                            kind: PathKind::Perimeter,
                            points: vec![[0.0, 0.0], [10.0, 0.0], [10.0, 10.0], [0.0, 0.0]],
                        },
                        Path { kind: PathKind::Infill, points: vec![[2.0, 2.0], [8.0, 2.0]] },
                    ],
                },
                Pass {
                    layer: 0,
                    tool: 1,
                    z: 3.0,
                    paths: vec![Path { kind: PathKind::Perimeter, points: vec![[20.0, 0.0], [30.0, 0.0]] }],
                },
            ],
            tool_colors: vec![[0, 0, 0], [255, 0, 0]],
            extent: [0.0, 0.0, 30.0, 10.0],
        }
    }

    #[test]
    fn writes_tool_changes_lifts_and_increasing_extrusion() {
        let cfg = Config::default();
        let g = write(&job(), &cfg, "test.png");
        assert!(g.starts_with("; generated by img2gcode"));
        assert!(g.contains("G28 ; home all axes"));
        assert!(g.contains("G1 Z5 F7800 ; lift nozzle"));
        assert!(g.contains(";LAYER_CHANGE\n;Z:3\n"));
        assert!(g.contains("; --- Tool 0 ---\nT0\nG92 E0\n"));
        assert!(g.contains("; --- Tool 1 ---\nT1\n"));
        assert!(g.contains(";TYPE:Solid infill"));
        assert!(g.contains("G1 Z4 F7800\nG1 X2 Y2 F7800\nG1 Z3 F7800\nG1 F1800\n"));
        assert!(g.trim_end().ends_with("M84 ; motors off"));
        // Extrusion grows within a pass.
        let es: Vec<f64> = g
            .lines()
            .take_while(|l| !l.contains("Tool 1"))
            .filter(|l| l.starts_with("G1 X"))
            .filter_map(|l| l.split(" E").nth(1))
            .map(|v| v.parse().unwrap())
            .collect();
        assert!(es.windows(2).all(|w| w[1] > w[0]));
        let per_mm = e_per_mm(&cfg);
        assert!((es[0] - 10.0 * per_mm).abs() < 1e-4);
    }

    #[test]
    fn parse_reads_back_what_write_wrote() {
        let cfg = Config::default();
        let tp = job();
        let back = parse(&write(&tp, &cfg, "x"));
        assert_eq!(back.passes.len(), 2);
        assert_eq!(back.passes[0].paths.len(), 2);
        assert_eq!(back.passes[0].paths[0].points, tp.passes[0].paths[0].points);
        assert_eq!(back.passes[0].paths[1].kind, PathKind::Infill);
        assert_eq!(back.passes[1].tool, 1);
        assert_eq!(back.extent, [0.0, 0.0, 30.0, 10.0]);
    }

    #[test]
    fn stats_count_print_travel_and_filament() {
        let cfg = Config::default();
        let s = stats(&job(), &cfg);
        let diag = 200f64.sqrt();
        assert!((s.print_mm - (20.0 + diag + 6.0 + 10.0)).abs() < 1e-9);
        // (0,0) -> (2,2), then (8,2) -> (20,0).
        assert!((s.travel_mm - (2f64.hypot(2.0) + 12f64.hypot(2.0))).abs() < 1e-9);
        assert!(s.filament_g > 0.0);
    }

    #[test]
    fn crlf_templates_are_written_as_lf() {
        let mut cfg = Config::default();
        cfg.gcode.start = "G28\r\nG92 E0\r\n".into();
        let g = write(&job(), &cfg, "x");
        assert!(!g.contains('\r'));
        assert!(g.contains(";\nG28\nG92 E0\n"));
    }

    #[test]
    fn numbers_are_trimmed() {
        assert_eq!(num(3.0), "3");
        assert_eq!(num(-0.0001), "0");
        assert_eq!(num(1.23456), "1.235");
    }
}
